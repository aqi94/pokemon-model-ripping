import json
import os
from datetime import date

from ..importers.za.trlgt import LightRig
from .catalog import SvLightCatalog, merge
from .rig_to_env import apply_delta, rig_to_env

# (preset id, label, area rig or None for master, weather delta rig or None)
SV_PRESETS: list[tuple[str, str, str | None, str | None]] = [
    ("sv_field_day", "SV field, clear day", None, None),
    ("sv_field_cloudy", "SV field, cloudy", None, "weather_cloudy"),
    ("sv_field_rain", "SV field, rain", None, "weather_rain"),
    ("sv_field_storm", "SV field, storm", None, "weather_storm"),
    ("sv_field_mist", "SV field, mist", None, "weather_mist"),
    ("sv_field_snow", "SV field, snowstorm", None, "weather_snowstorm"),
    ("sv_field_sandstorm", "SV field, sandstorm", None, "weather_sandstorm"),
    ("sv_interior", "SV interior", "fel_interior", None),
    ("sv_interior_24h", "SV interior (24 h shop)", "fel_interior_24h", None),
    ("sv_interior_cloudy", "SV interior, cloudy outside", "fel_interior", "weather_inside_cloudy"),
    ("sv_classroom", "SV academy classroom", "fel_a_sch_class", None),
    ("sv_academy_entrance", "SV academy entrance", "fel_a_sch_entrance01", None),
    ("sv_raid", "SV Tera Raid", "fel_raidbattle", None),
    ("sv_picnic", "SV picnic", "fel_picnic", None),
    ("sv_cave_cloudy", "SV cave", None, "weather_cave_cloudy"),
    ("sv_cutscene_01", "SV cutscene spl_01", "spl_01", None),
    ("sv_cutscene_07", "SV cutscene spl_07", "spl_07", None),
]


def effective_rig(cat: SvLightCatalog, area: str | None, weather: str | None) -> LightRig:
    rig = cat.master()
    if area:
        rig = merge(rig, cat.load(area))
    if weather:
        rig = apply_delta(rig, cat.load(weather))
    return rig


def _probe_means(cat: SvLightCatalog, area: str | None):
    name = area or "master"
    try:
        from .probes import hemisphere_means, read_cube
        p = cat.find(name).texture("probemain_diffuse.bntx")
        if not p:
            return None, None
        with open(p, "rb") as f:
            sky, ground = hemisphere_means(read_cube(f.read()))
        if float(sky.max()) < 1e-3:  # decoder returned black (BC6H signed unsupported)
            return None, None
        return tuple(float(v) for v in sky), tuple(float(v) for v in ground)
    except Exception:
        return None, None


def build_presets(cat: SvLightCatalog, category: int = 5) -> list[dict]:
    master = cat.master()
    out = []
    for pid, label, area, weather in SV_PRESETS:
        try:
            rig = effective_rig(cat, area, weather)
        except KeyError as e:
            print(f"skip {pid}: {e}")
            continue
        sky, ground = _probe_means(cat, area)
        env, prov = rig_to_env(rig, category, master, rig_name=" + ".join(x for x in (area or "master", weather) if x),
                               probe_sky=sky, probe_ground=ground)
        twin = next((q for q in out if q["env"] == env), None)
        if twin is not None:  # e.g. storm/mist/snow only differ in sky and fog, which category 5 never sees
            print(f"skip {pid}: identical to {twin['id']} for category {category}")
            twin["provenance"].notes.append(f"also {pid} ({prov.rig})")
            continue
        out.append({"id": pid, "label": label, "game": "sv", "env": env, "provenance": prov})
    return out


def _ts_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return "'" + v.replace("'", "\\'") + "'"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k}: {_ts_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


def presets_ts(presets: list[dict], category: int) -> str:
    lines = [
        "// GENERATED by `python -m pipeline --game sv lights presets` from the SV light rigs (SV-Everything.7z romfs/env).",
        "// Do not edit; see pipeline/lighting/rig_to_env.py (mapping v1, unvalidated against screenshots) and docs/lighting_rigs.md.",
        f"// Material category {category}; intensities normalised so master == Studio levels. Generated {date.today().isoformat()}.",
        "import type { LightingPreset } from './environment';",
        "",
        "export const SV_PRESETS: LightingPreset[] = [",
    ]
    for p in presets:
        pv = p["provenance"]
        extra = f"; rig key colour x intensity {pv.key_rig}" if pv.key_rig else ""
        ang = f"; sun from az {pv.key_angles[0]} el {pv.key_angles[1]} deg (world)" if pv.key_angles else ""
        notes = ("; " + "; ".join(pv.notes)) if pv.notes else ""
        lines.append(f"  // {pv.rig}{extra}{ang}{notes}")
        lines.append(f"  {{ id: {_ts_value(p['id'])}, label: {_ts_value(p['label'])}, game: 'sv', env: {_ts_value(p['env'])} }},")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def write_sv_presets(cat: SvLightCatalog, ts_path: str, category: int = 5) -> str:
    presets = build_presets(cat, category)
    os.makedirs(os.path.dirname(ts_path) or ".", exist_ok=True)
    with open(ts_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(presets_ts(presets, category))
    side = os.path.splitext(ts_path)[0] + ".json"
    with open(side, "w", encoding="utf-8") as f:
        json.dump([{k: v for k, v in p.items() if k != "provenance"} for p in presets], f, indent=1)
    return ts_path
